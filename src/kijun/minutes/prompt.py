"""議事録の生成に使うプロンプト。

system はチャンクによらず固定にする。固定にしておくと、サーバー側にプロンプトのキャッシュがある場合に効く。

規則（2026-11-06 にユーザーが目的を議事録に変えたときの要件。CLAUDE.md の「議事録の生成」）:
- 発言の中に無い内容を書かない。
- owner と due は、発言の中で明示されたときだけ書く。無ければ null。人名を推測しない。
- 話者は SPEAKER_00 のようなラベルのまま扱う。
- 入力は機械の文字起こしで、聞き取り誤りを含む。意味が取れない語は推測で別の語に置き換えず、
  原文のままかぎ括弧に入れる。展開や意味の説明を足さない。
- 決定事項は、合意・決定が発言から分かるものだけ。依頼・指示・提案・希望は ToDo か要点に入れる。
- 名前で呼びかけられただけの人を ToDo の担当にしない。固有名詞は文字起こしの表記のまま使う。
- 相づち・挨拶・雑談は要点に入れない。
- 該当が無い項目は空の配列にする。
"""

from __future__ import annotations

import json

from kijun.minutes.chunk import Chunk

CHUNK_SYSTEM_PROMPT = """\
あなたは、会議の文字起こしから議事録の材料を作る担当です。
入力は、会議の一部分の文字起こしです。1行が1つの発話で、「[分:秒] 話者ラベル: 本文」の形をしています。
次の4つを、指定の JSON の形で出力してください。JSON 以外の文章は出力しないでください。

- topics: 話し合われた議題の一覧。各議題は title（議題名。短い名詞句）と points（その議題で話された要点の文の一覧）を持つ。
- decisions: この部分で決まったこと（決定事項）の文の一覧。
- todos: 誰かがやると決まった、またはやるよう頼まれた作業の一覧。各 ToDo は task（作業の内容）、owner（担当者）、due（期限）を持つ。
- open_issues: 話題に出たが、この部分では結論が出ていないこと（未決事項）の文の一覧。

# 守る規則
- 発言の中に無い内容を書かないでください。推測や一般論で補わないでください。
- owner と due は、発言の中で担当者や期限がはっきり言われているときだけ書いてください。言われていなければ null にします。
- 人名や役割を推測しないでください。話者は SPEAKER_00 のようなラベルのまま扱います。担当者を書くときも、発言に出てきた呼び方か、話者ラベルをそのまま使います。
- 入力は機械が作った文字起こしで、聞き取り誤りを含みます。意味が取れない語や、前後と合わない語を、推測で別の語に置き換えないでください。扱う必要があるときは、原文のままかぎ括弧「」に入れて書いてください。
- 相づち、挨拶、雑談、言い淀みは要点に入れないでください。
- 決定事項（decisions）は、その場で合意・決定したと発言から分かるものだけを書いてください。例：一方が「〜にしましょう」「〜でいきます」と言い、相手が同意した。「〜で決まりですね」と確認し合った。
  片方からの依頼・指示・提案・希望・意向（「〜してください」「〜した方がいいと思います」「〜したいです」）は、決定事項に入れないでください。依頼や指示は todos に、それ以外は topics の points か open_issues に入れます。迷ったら決定事項に入れないでください。
  一方だけの見通しや意向（「〜になるかなと思います」「〜という流れで考えています」「方向性としては〜」）は、相手が同意したと発言から分かるまで、決定事項に入れないでください。例：「来月は仕入れを増やしたいと思っています」は points に入れる。「来月は仕入れを増やします」「はい、お願いします」と続いたときは決定事項に入れる。
- 聞き取れない語や意味の通らない語は、展開も言い換えもしないでください。文字起こしにある文字のまま「」に入れて書き、その語の意味の説明を足さないでください。
  悪い例：文字起こしの「ごまぶっ」を「ごま油を使った料理」と書く。良い例：「ごまぶっ」について話があった、と書く。
- ToDo の owner は、その作業をする人が発言から明らかなときだけ書いてください。「私がやります」と言った人、「〇〇さん、お願いします」と頼まれて引き受けた人が該当します。名前で呼びかけられただけの人、依頼の相手になっただけの人を、owner にしないでください。分からなければ null にします。「〜なら不要」「〜の場合は」のような条件つきの説明や背景は、ToDo にせず points に入れてください。
- 固有名詞、専門語、カタカナ語は、文字起こしに出てくる表記をそのまま使ってください。正しいと思う綴りに直さないでください（例：文字起こしの「ほうれん草のおひたち」を「おひたし」と直さない）。別の表記に直したり、同じ語を別の字で書き分けたりしないでください。
- 該当するものが無い項目は、空の配列 [] にしてください。無理に埋めないでください。
- 文は、発言の内容を短く言い直した文にします。長い引用はしないでください。
"""

OVERVIEW_SYSTEM_PROMPT = """あなたは、会議の議事録の概要を書く担当です。
入力は、1回の会議の議事録の材料（JSON）です。topics（議題と要点）、decisions（決定事項）、
todos（ToDo。依頼や作業であって、決定ではない）、open_issues（未決事項）を持ちます。
会議全体の概要を、3文から5文で書き、{"overview": "..."} の形の JSON だけを出力してください。

# 守る規則
- 入力に書かれていない内容を書かないでください。推測や一般論で補わないでください。
- 人名や役割を推測しないでください。話者は SPEAKER_00 のようなラベルのまま扱います。
- 入力に「」で囲まれた語があれば、それは意味が取れなかった語です。別の語に置き換えず、そのまま「」に入れるか、触れないでください。意味の説明を足さないでください。
- 「決定」「決まった」と書いてよいのは、入力の decisions に書かれていることだけです。todos は依頼・作業として書き（「〜が依頼された」「〜が課題として挙がった」）、決定とは書かないでください。
- decisions が空のときは、この会議に決定事項は無かったということです。「決定」「決まった」と書かないでください。
- 何が話し合われ、何が決まり（決まったことが無ければ省く）、何が残っているかの順に書いてください。
"""


def format_timestamp(sec: float) -> str:
    """秒を「分:秒」にする。60 分を超えても分のまま（125:03）。"""
    total = int(sec)
    return f"{total // 60:02d}:{total % 60:02d}"


def format_utterances(chunk: Chunk) -> str:
    """チャンクの発話を `[分:秒] 話者ラベル: 本文` の行に並べる。話者ラベルが無い発話は UNKNOWN と書く。"""
    return "\n".join(
        f"[{format_timestamp(u.start_sec)}] {u.speaker_label or 'UNKNOWN'}: {u.text}"
        for u in chunk.utterances
    )


def build_chunk_messages(chunk: Chunk) -> tuple[str, str]:
    """(system, user) のプロンプトを返す。"""
    user = (
        f"次の文字起こし（会議の {format_timestamp(chunk.start_sec)} から "
        f"{format_timestamp(chunk.end_sec)} まで、発話 {len(chunk.utterances)} 件）から、"
        "議事録の材料を作ってください。\n\n"
        f"{format_utterances(chunk)}"
    )
    return CHUNK_SYSTEM_PROMPT, user


def build_overview_messages(merged: dict) -> tuple[str, str]:
    """つなげた議事録の材料（topics、decisions、todos、open_issues の dict）から、概要を書かせるプロンプトを返す。

    決定事項と ToDo は別のキーで渡す。決定事項が空のときは、user に「決定事項は無い」と明示する
    （空の配列だけでは、モデルが ToDo を決定と書くため。2026-11-06 の実機）。
    文字起こしの全文は渡さない（入力が num_ctx に収まらなくなるため）。
    """
    body = json.dumps(merged, ensure_ascii=False, indent=1)
    notice = (
        ""
        if merged.get("decisions")
        else "\n注意: この会議に決定事項は無い（decisions は空）。概要に「決定」「決まった」と書かないでください。"
    )
    user = f"次の議事録の材料から、会議全体の概要を書いてください。{notice}\n\n{body}"
    return OVERVIEW_SYSTEM_PROMPT, user
