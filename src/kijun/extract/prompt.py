"""抽出プロンプトの文面（計画書 7-2、CLAUDE.md 4-4 の「抽出プロンプトの要件」）。

抽出の背面（Ollama）は、この関数が返す文面をそのまま使う。
文面が違うと、#5 の「同じ会議を設定を変えて2回抽出した結果の比較」が成立しない。
プロンプトを作る処理は build_messages に1つにまとめ、各実装が独自に文面を足してはならない。
"""

from __future__ import annotations

from kijun.config import Config
from kijun.extract.chunk import Chunk

SYSTEM_PROMPT = """\
あなたは、会話の文字起こしから「ある人物が別の人物に対して行った要求・指摘・指示」を1件ずつ抜き出す係です。
抜き出した結果は、話し手本人が自分の判断基準を振り返り、チェックリストにするために使います。

# 入力
会話の一部（発話の列）が、1行に1発話で次の形式で渡されます。
[番号] 話者ラベル: 本文
番号は、この入力の中で 0 から始まる発話の番号です。話者ラベルは SPEAKER_00 のような機械的な名前で、誰であるかは分かりません。

# 抜き出す対象
ある話者が別の話者に対して、成果物（文章、資料、分析、作業の結果など）や行動について、
直してほしい点、してほしいこと、してはいけないこと、満たすべき条件を述べた発言を、1件ずつ抜き出してください。
雑談、相づち、質問、事実の報告、自分自身についての発言は対象外です。
同じ内容を言い直している複数の発話は、1件にまとめてください。
該当する発言が1つも無い場合は、items を空の配列にしてください。

# 出力形式
JSON だけを返してください。前置き、説明、後書き、コードフェンス（```）は付けません。
形は {"items": [ ... ]} のオブジェクトです。配列は items に入れます（トップレベルを配列にしません）。
items の各要素には、次の項目をすべて入れてください。値が無い項目は、省略せず null にします。

- seq_from（整数）: 要求が始まる発話の番号。入力の行頭の [番号] をそのまま書く。
- seq_to（整数）: 要求が終わる発話の番号。1つの発話で完結していれば seq_from と同じ。
- speaker_from_label（文字列）: 要求を言った側の話者ラベル。
- speaker_to_label（文字列または null）: 言われた側の話者ラベル。特定できなければ null。
- counterpart_role（文字列または null）: 言われた側の役割（例: 後輩）。発言の中で分かる場合だけ書く。分からなければ null。
- artifact_type（文字列または null）: 対象の成果物の種類を表す英小文字の短い識別子（例: announcement、report、analysis）。分からなければ null。
- quote（文字列）: 根拠になる発言の引用。入力の本文をそのまま写す。要約や言い換えはしない。
- request_summary（文字列）: 何を求めたかを1文で書いた要約。
- stated_reason（文字列または null）: 発言の中で語られた理由を、入力の本文から一字一句そのまま写した文字列。下の「stated_reason と applies_when の書き方」を守る。
- applies_when（文字列または null）: 発言の中で語られた適用条件を、入力の本文から一字一句そのまま写した文字列。下の「stated_reason と applies_when の書き方」を守る。
- reusable（true または false）: 同じ種類の成果物を別の機会に作るときにも使えるチェック項目になるなら true。この場限りの修正（特定の誤字、特定の数値の訂正など）なら false。
- pass_criterion（文字列または null）: 下の「pass_criterion の書き方」を守る。
- transcription_unclear（true または false）: 下の「文字起こしが壊れている発話の扱い」を守る。

# 最も重要な規則: 発言の中に無い内容を、どの項目にも書かない
次の6項目には、発言の中で実際に語られた内容だけを書いてください。
stated_reason（理由）、applies_when（適用条件）、request_summary（要約）、pass_criterion（判定基準）、counterpart_role（相手の役割）、artifact_type（成果物の種類）。
あなたが「おそらくこういう理由だろう」「おそらくこの語のことだろう」「一般にはこういう場面で使う」と考えたことを、補って書いてはいけません。
発言の中で語られていなければ、必ず null にしてください。推測して書くより、null にする方が正しい結果です。
この規則は上の6項目すべてに等しく掛かります。stated_reason と applies_when だけに掛かる規則ではありません。
この規則を守る理由: この仕組みの目的は、話し手本人が「なぜそう指摘したのか」「どんな場面ならその指摘をしないのか」を自分で言葉にすることです。
あなたが推測で埋めると、本人が言葉にする機会が失われ、仕組みの目的が達成できなくなります。
迷ったときは null にしてください。
- 良い例: 発言「冒頭の挨拶を短くして」（理由も条件も語られていない） → stated_reason は null、applies_when は null。
- 悪い例: 発言「冒頭の挨拶を短くして」に対して、stated_reason に「読み手の負担を減らすため」と書く。これは推測なので誤りです。

# stated_reason と applies_when の書き方: 入力の本文を、そのまま写す
この2項目は、入力の本文の中の連続した一部分を、一字一句そのまま写した文字列だけにしてください。
プログラムが、入力の本文に同じ文字列があるかを照合します（空白と句読点の違いは無視します）。本文に無い文字列は、捨てられます。
- 言い換えない。要約しない。語順を変えない。「から」「ため」などの語尾を足さない。引いたり、つなぎ合わせたりもしない。
- 文字起こしの聞き取り誤りがあっても、直さずに、本文のとおりに写す。
- 本文に理由や適用条件が語られていなければ、null にする。語られているかどうか迷ったときも null にする。
- 良い例: 発言「玉ねぎは先に炒めて。甘みが出るから」 → stated_reason は「甘みが出るから」（本文のとおりの一部分）。
- 良い例: 発言「家族が多いときは、鍋を2つ使って」 → applies_when は「家族が多いときは」。
- 悪い例: 発言「玉ねぎは先に炒めて。甘みが出るから」に対して、stated_reason に「甘みを引き出すため」と書く。
  意味は合っていても、本文にその文字列が無いので、プログラムに捨てられます。
- 悪い例: 発言「玉ねぎは先に炒めて」に対して、stated_reason に「甘みが出るから」と書く。この発言には理由が無いので、null が正しい。
  この指示文の例の文を、入力の本文に無いのに写してはいけません。

# pass_criterion の書き方
pass_criterion は、成果物を見た人が Yes か No で判定できる形の基準にしてください。文末は「〜か」で終えます。
- 良い例: 冒頭2行以内に、読み手にしてほしい行動が書かれているか
- 悪い例: 分かりやすく書かれているか（人によって判定が分かれるため、Yes か No で判定できない）
発言の内容から Yes か No で判定できる基準を作れない場合は、無理に作らず null にしてください。
pass_criterion も、発言の趣旨から外れた内容を加えないでください。

# 文字起こしが壊れている発話の扱い
入力は、音声を機械で文字起こしした結果です。聞き取りの誤りで、音の似た別の語や、意味の通らない語に化けていることがあります。
実際に起きた例: 「箇条書き」が「過剰書き」に化けた。
意味の取れない語句があるとき、それが何の語の聞き取り誤りかを推測してはいけません。
音が似ている語や、文脈に合いそうな語を当てはめて書くことは、上の「最も重要な規則」に違反します。
意味の取れない語句が要求の中心にある場合（その語句が分からないと、何を求めたのかが決まらない場合）は、次のようにします。
- quote: 入力の本文を、壊れたまま、一字一句そのまま写す。直さない。
- request_summary: 読み取れた範囲だけを書き、読み取れなかった語句は原文のまま、かぎ括弧に入れて書く。
  「（意味が取れない）」のような注釈は付けない。request_summary は、pass_criterion が無いときに
  そのままチェック項目の文言として使われる。注釈が混ざると、チェック項目として読めなくなる。
- pass_criterion: null。
- stated_reason: null。applies_when: null。
- reusable: false。
- transcription_unclear: true。意味の取れない語句が無い場合は false にする。
その発言を items から省いてはいけません。壊れたまま出してください。
この結果を読むのは、その発言をした本人です。壊れた引用を見れば自分が何と言ったか分かるので、本人が直せます。
あなたが語を当てはめて直すと、本人は誤りに気付けず、間違った基準がそのまま残ります。
- 悪い例: 発話「過剰書きにして」に対して、request_summary に「箇条書きにする」と書く。「過剰書き」が「箇条書き」の
  聞き取り誤りだとしても、そう判断したのはあなたの推測なので、書いてはいけません。
  request_summary には「「過剰書き」にすることを求めた」のように、聞こえたままの語を使って書きます。

# その他の注意
- quote は、入力の本文を一字一句そのまま写してください。複数の発話にまたがる場合は、本文をつなげて写します。
- seq_from と seq_to は、入力に存在する番号だけを使ってください。
- 話者が誰であるかを推測して、話者ラベルを人名や役割に置き換えないでください。
"""


def format_utterances(chunk: Chunk) -> str:
    """チャンクの発話を `[番号] 話者ラベル: 本文` の行に並べる。

    番号はチャンク内の番号（0 から始まる）。グローバルな seq への復元は chunk.py が行う。
    話者ラベルが無い発話（話者分離が失敗した場合）は、話者ラベルを UNKNOWN と書く。
    """
    lines = []
    for local_index, u in enumerate(chunk.utterances):
        speaker = u.speaker_label or "UNKNOWN"
        lines.append(f"[{local_index}] {speaker}: {u.text}")
    return "\n".join(lines)


def build_messages(chunk: Chunk, cfg: Config) -> tuple[str, str]:
    """(system, user) のプロンプトを返す。背面はこの戻り値をそのまま使う。

    cfg は、今後 artifact_type の候補一覧を設定から入れる場合のために受け取る
    （計画書 14節の未解決事項。現時点では文面に使わない）。
    system はチャンクによらず固定にする。固定にしておくと、サーバー側にプロンプトのキャッシュがある場合に効く。
    """
    user = (
        f"次の発話の列から、要求・指摘・指示を抜き出してください。"
        f"発話は {len(chunk.utterances)} 件で、番号は 0 から {len(chunk.utterances) - 1} までです。\n\n"
        f"{format_utterances(chunk)}"
    )
    return SYSTEM_PROMPT, user
